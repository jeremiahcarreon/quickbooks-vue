/** Where to open a transaction of a given type (for links from lists and centers). */
export function formPathFor(type: string, id?: string): string | null {
  const spec = specByType(type);
  const special = SPECIAL_FORMS.find((s) => s.type === type && s.editable);
  const slug = spec?.slug ?? special?.slug;
  if (!slug) return null;
  return id ? `/transactions/${slug}/${encodeURIComponent(id)}` : `/transactions/${slug}/new`;
}
