const BY_SLUG = new Map(SPECS.map((s) => [s.slug, s]));
const BY_TYPE = new Map(SPECS.map((s) => [s.type, s]));

export function specBySlug(slug: string): TxnSpec | undefined {
  return BY_SLUG.get(slug);
}

export function specByType(type: string): TxnSpec | undefined {
  return BY_TYPE.get(type);
}

